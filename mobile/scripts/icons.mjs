// Generates Android and iOS launcher icons and splash screens for both apps from the web app's SVG icons
// (app/customer/icon.svg, app/rider/icon.svg) and the logo's pin mark. Run: npm run icons
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const sharp = createRequire(path.join(root, "package.json"))("sharp"); // the web app already ships sharp

const APPS = {
  customer: { icon: "app/customer/icon.svg", splash: "#0b5cff" },
  rider: { icon: "app/rider/icon.svg", splash: "#1e3a8a" },
};
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const SPLASH = { mdpi: [320, 480], hdpi: [480, 800], xhdpi: [720, 1280], xxhdpi: [960, 1600], xxxhdpi: [1280, 1920] };

// The pin + "R" from public/ridewallah-logo.svg, drawn white on the splash colour.
const PIN = (bg) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="7 4 42 49">
  <path d="M28 4C16.4 4 7 13.2 7 24.6 7 39.4 28 52.6 28 52.6s21-13.2 21-28C49 13.2 39.6 4 28 4z" fill="#fff"/>
  <path d="M21.4 37V15h8.2c4.8 0 7.7 2.5 7.7 6.6 0 3-1.7 5.1-4.4 6L38 37h-5.2l-4.6-8.8h-2.2V37z M26 24.4h3.5c2 0 3.2-1 3.2-2.8s-1.2-2.8-3.2-2.8H26z" fill="${bg}"/>
</svg>`;

const png = (svg, w, h = w) => sharp(Buffer.from(svg), { density: 600 }).resize(w, h, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();

for (const [app, cfg] of Object.entries(APPS)) {
  const res = path.join(here, "..", app, "android/app/src/main/res");
  const svg = fs.readFileSync(path.join(root, cfg.icon), "utf8");
  const stops = [...svg.matchAll(/stop-color="(#[0-9a-fA-F]{3,8})"/g)].map((m) => m[1]);
  const inner = svg.replace(/<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const content = inner.replace(/<rect[^>]*\/>/, ""); // the glyph without the rounded-square background
  const defs = (inner.match(/<defs>[\s\S]*?<\/defs>/) ?? [""])[0];

  // Adaptive icon: gradient background layer + glyph foreground inside the 66/108 safe zone.
  const foreground = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-22 -22 108 108">${content}</svg>`;
  const round = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${defs}<circle cx="32" cy="32" r="32" fill="url(#g)"/>${content.replace(defs, "")}</svg>`;
  for (const [d, k] of Object.entries(DENSITIES)) {
    const dir = path.join(res, `mipmap-${d}`);
    fs.writeFileSync(path.join(dir, "ic_launcher.png"), await png(svg, Math.round(48 * k)));
    fs.writeFileSync(path.join(dir, "ic_launcher_round.png"), await png(round, Math.round(48 * k)));
    fs.writeFileSync(path.join(dir, "ic_launcher_foreground.png"), await png(foreground, Math.round(108 * k)));
    const [w, h] = SPLASH[d];
    for (const [orient, W, H] of [["port", w, h], ["land", h, w]]) {
      const mark = await png(PIN(cfg.splash), Math.round(Math.min(W, H) * 0.32));
      const out = await sharp({ create: { width: W, height: H, channels: 4, background: cfg.splash } })
        .composite([{ input: mark, gravity: "center" }]).png().toBuffer();
      fs.writeFileSync(path.join(res, `drawable-${orient}-${d}`, "splash.png"), out);
    }
  }
  const mark = await png(PIN(cfg.splash), 110);
  fs.writeFileSync(path.join(res, "drawable", "splash.png"),
    await sharp({ create: { width: 480, height: 320, channels: 4, background: cfg.splash } }).composite([{ input: mark, gravity: "center" }]).png().toBuffer());

  fs.writeFileSync(path.join(res, "drawable", "ic_launcher_background.xml"), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/icons.mjs from ${cfg.icon} -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="315" android:startColor="${stops[0]}" android:endColor="${stops[1]}" />
</shape>
`);
  fs.writeFileSync(path.join(res, "mipmap-anydpi-v26", "ic_launcher.xml"), `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
`);
  fs.copyFileSync(path.join(res, "mipmap-anydpi-v26", "ic_launcher.xml"), path.join(res, "mipmap-anydpi-v26", "ic_launcher_round.xml"));
  // iOS (when the project exists): one opaque, square 1024 icon (iOS rounds the corners itself) and the
  // 2732×2732 splash used by Capacitor's launch screen.
  const ios = path.join(here, "..", app, "ios/App/App/Assets.xcassets");
  if (fs.existsSync(ios)) {
    const square = svg.replace(/rx="[^"]*"/, 'rx="0"');
    fs.writeFileSync(path.join(ios, "AppIcon.appiconset/AppIcon-512@2x.png"),
      await sharp(Buffer.from(square), { density: 1200 }).resize(1024, 1024).flatten({ background: stops[1] }).png().toBuffer());
    const mark = await png(PIN(cfg.splash), 640);
    const splash = await sharp({ create: { width: 2732, height: 2732, channels: 4, background: cfg.splash } })
      .composite([{ input: mark, gravity: "center" }]).png().toBuffer();
    for (const f of ["splash-2732x2732.png", "splash-2732x2732-1.png", "splash-2732x2732-2.png"]) {
      fs.writeFileSync(path.join(ios, "Splash.imageset", f), splash);
    }
  }
  console.log(`${app}: icons and splash screens written (gradient ${stops.join(" → ")})`);
}
